create table if not exists public.travel_requests (
  id bigint generated by default as identity primary key,
  request_type text not null check (request_type in ('flight','hotel','visa','stopover','package','other')),
  customer_name text not null,
  phone text not null,
  origin text,
  destination text,
  departure_date date,
  return_date date,
  passengers integer not null default 1 check (passengers between 1 and 20),
  nationality text,
  stopover_country text,
  stopover_days integer check (stopover_days is null or stopover_days between 1 and 90),
  details text,
  status text not null default 'NEW' check (status in ('NEW','REVIEWING','QUOTED','AWAITING_PAYMENT','PAID','CONFIRMED','COMPLETED','CANCELLED')),
  payment_status text not null default 'UNPAID' check (payment_status in ('UNPAID','RECEIPT_SUBMITTED','PAID','REFUNDED')),
  quoted_cost_etb numeric(14,2) not null default 0 check (quoted_cost_etb >= 0),
  quoted_price_etb numeric(14,2) not null default 0 check (quoted_price_etb >= 0),
  extra_expenses_etb numeric(14,2) not null default 0 check (extra_expenses_etb >= 0),
  admin_notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists travel_requests_created_at_idx on public.travel_requests (created_at desc);
create index if not exists travel_requests_status_idx on public.travel_requests (status);

-- The server uses the Supabase service-role key; never expose it in browser code.
-- Keep direct table access restricted. If you later add customer-side Supabase access,
-- create explicit RLS policies rather than enabling public reads/writes.
alter table public.travel_requests enable row level security;
